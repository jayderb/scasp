package com.scasp.persistence;

import org.junit.jupiter.api.Test;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;

/** Pure unit test (no database needed). */
class SqlScriptRunnerTest {
    @Test void splitsStatementsAndSkipsComments() {
        List<String> s = SqlScriptRunner.split("-- comment\nCREATE TABLE a (\n  id INT\n);\n\nINSERT INTO a VALUES (1);\n-- end\n");
        assertEquals(2, s.size());
        assertTrue(s.get(0).startsWith("CREATE TABLE a")); assertEquals("INSERT INTO a VALUES (1)", s.get(1));
    }
    @Test void packagedSchemaContainsAllTables() throws Exception {
        String schema = new String(getClass().getClassLoader().getResourceAsStream("db/schema.sql").readAllBytes());
        for (String t : new String[]{"app_user", "students", "courses", "registrations", "waiting_list", "service_request", "announcement", "campus_service", "audit_event"})
            assertTrue(schema.contains("CREATE TABLE " + t + " ("), t);
        assertTrue(schema.contains("ENGINE=InnoDB")); assertTrue(schema.contains("AUTO_INCREMENT"));
        assertFalse(schema.contains("GENERATED BY DEFAULT AS IDENTITY"), "H2/PostgreSQL syntax removed");
    }
}
